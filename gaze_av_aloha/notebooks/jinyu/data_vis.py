def preprocess_observation(observations: dict[str, np.ndarray]) -> dict[str, Tensor]:
    """Convert environment observation to LeRobot format observation.
    Args:
        observation: Dictionary of observation batches from a Gym vector environment.
    Returns:
        Dictionary of observation batches with keys renamed to LeRobot format and values as tensors.
    """
    return_observations = {}
    imgs = {f"observation.images.{key}": img for key, img in observations["images"].items()}

    for imgkey, img in imgs.items():
        img = torch.from_numpy(img.copy()).unsqueeze(0)

        # sanity check that images are channel last
        _, h, w, c = img.shape
        assert c < h and c < w, f"expect channel last images, but instead got {img.shape=}"

        # sanity check that images are uint8
        assert img.dtype == torch.uint8, f"expect torch.uint8, but instead {img.dtype=}"

        # convert to channel first of type float32 in range [0,1]
        img = einops.rearrange(img, "b h w c -> b c h w").contiguous()
        img = img.type(torch.float32)
        img /= 255

        return_observations[imgkey] = img

    return return_observations

def capture_images_and_generate_video(env, num_images=50, video_path="output.mp4"):
    # 初始化环境
    env.reset()
    
    # 初始化视频帧列表
    frames = []

    # 连续获取50张图片
    for _ in tqdm(range(num_images)):
        # 获取当前环境的观察值
        # call_observations[_]
        # for k in range(2):
        #     observation, info = env.step_action(actions[k])
        #     time.sleep(REAL_DT)
        observation, info = env.step_action(all_observations[_])
        #time.sleep(REAL_DT)
        
        
        # 预处理观察值
        observation = preprocess_observation(observation)
        
        # 获取左眼相机的图像
        img = observation["observation.images.left_eye_cam"].squeeze(0).permute(1, 2, 0).numpy()
        
        # 应用数据增强
        img = image_transforms_augmentation(img)
        
        # 将处理后的图像转换为 NumPy 格式并添加到帧列表
        img = (img.permute(1, 2, 0).numpy() * 255).astype(np.uint8)
        frames.append(img)
        
        # 等待一段时间以模拟真实环境
        time.sleep(REAL_DT)
    
    # 生成视频
    imageio.mimsave(video_path, frames, fps=FPS)
    print(f"Video saved to {video_path}")

def main():
    # 初始化环境
    env = RealEnv(init_node=True)
    
    # 捕获图像并生成视频
    capture_images_and_generate_video(env, num_images=50, video_path="output.mp4")

